from __future__ import annotations

import math
import re
from pathlib import Path

from .coordinate_converter import convert_local_matrix
from .matrix_converter import source_local_bind


def _number(value: float, digits: int = 8) -> str:
    if abs(value) < 0.5 * (10 ** -digits):
        value = 0.0
    text = f"{value:.{digits}f}".rstrip("0").rstrip(".")
    if text in {"", "-0", "0"}:
        return "0.0"
    return text if "." in text else text + ".0"


def _class_name(resource_path: str) -> str:
    pieces = re.findall(r"[A-Za-z0-9]+", resource_path)
    stem = "".join(piece[:1].upper() + piece[1:] for piece in pieces)
    return (stem or "Echo") + "Rig"


def _bone_call(armature, schema, index: int) -> str:
    entry = schema.bones[index]
    local = convert_local_matrix(source_local_bind(armature, schema, index))
    location, rotation, scale = local.decompose()
    euler = rotation.to_euler("XYZ")
    fields = [f'Bone("{entry.runtime_name}"']
    if entry.parent_index >= 0:
        parent = schema.bones[entry.parent_index].runtime_name
        fields.append(f'parent: "{parent}"')
    for name, value in zip(("x", "y", "z"), location):
        fields.append(f'{name}: "{_number(float(value))}"')
    for name, value in zip(("rotX", "rotY", "rotZ"), euler):
        fields.append(f'{name}: "{_number(math.degrees(float(value)))}"')
    for name, value in zip(("scaleX", "scaleY", "scaleZ"), scale):
        fields.append(f'{name}: "{_number(float(value))}"')
    return ", ".join(fields) + ")"


def render_rig_definition(armature, schema) -> str:
    namespace, _separator, resource_path = schema.rig_resource_id.partition(":")
    lines = []
    for index in range(len(schema.bones)):
        suffix = "," if index < len(schema.bones) - 1 else ""
        lines.append("                " + _bone_call(armature, schema, index) + suffix)
    sockets = []
    runtime_names = set(schema.runtime_names)
    if "right_item" in runtime_names:
        sockets.append('Socket("main_hand", bone: "right_item")')
    elif "right_hand" in runtime_names:
        sockets.append('Socket("main_hand", bone: "right_hand")')
    elif "right_forearm" in runtime_names:
        sockets.append('Socket("main_hand", bone: "right_forearm")')
    if "left_item" in runtime_names:
        sockets.append('Socket("off_hand", bone: "left_item")')
    elif "left_hand" in runtime_names:
        sockets.append('Socket("off_hand", bone: "left_hand")')
    elif "left_forearm" in runtime_names:
        sockets.append('Socket("off_hand", bone: "left_forearm")')
    socket_lines = ",\n".join("                " + value for value in sockets)
    return f'''// Generated by Echo Animation Exporter 3.0.2
namespace JDH.Animation;

class {_class_name(resource_path)} : AnimationRigResource
{{
    public override AnimationRigDef Build()
    {{
        return AnimationRig("{schema.rig_resource_id}",
            kind: "SKINNED_MESH", skin: "CLASSIC",
            bones: [
{chr(10).join(lines)}
            ],
            sockets: [
{socket_lines}
            ]);
    }}
}}
'''


def rig_definition_path_for_skin(skin_path: Path, rig_resource_id: str) -> Path:
    skin_path = skin_path.resolve()
    namespace, separator, resource_path = rig_resource_id.partition(":")
    if not separator:
        raise RuntimeError(f"Invalid rig resource ID: {rig_resource_id}")
    parts = list(skin_path.parts)
    lowered = [part.lower() for part in parts]
    try:
        assets_index = lowered.index("assets")
    except ValueError:
        assets_index = -1
    if assets_index >= 0:
        pack_root = Path(*parts[:assets_index])
        resource_parts = resource_path.strip("/").split("/")
        filename = resource_parts[-1] + ".animation-rig.es"
        return (
            pack_root
            / "data"
            / namespace
            / "echo_animation"
            / "animation_rigs"
            / Path(*resource_parts[:-1])
            / filename
        )
    return skin_path.with_name(resource_path.rstrip("/").split("/")[-1] + ".animation-rig.es")


def write_rig_definition(skin_path, armature, schema) -> Path:
    path = rig_definition_path_for_skin(Path(skin_path), schema.rig_resource_id)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_rig_definition(armature, schema), encoding="utf-8", newline="\n")
    return path
