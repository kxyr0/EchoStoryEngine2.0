from __future__ import annotations

from .model import ExportAnimationModel, ExportKey, ExportSegment
from .naming import class_name, identifier


HEADER = "// GENERATED BY ECHO BLENDER ADD-ON.\n// MANUAL CHANGES MAY BE OVERWRITTEN."
ITEM_MARKERS = {
    "echo_item_attachments:attach_left_hand",
    "echo_item_attachments:attach_right_hand",
    "echo_item_attachments:release",
    "echo_item_attachments:detach",
}


def _number(value: float, digits: int = 6) -> str:
    if abs(value) < 0.5 * (10 ** -digits):
        value = 0.0
    text = f"{value:.{digits}f}".rstrip("0").rstrip(".")
    return (text if "." in text else text + ".0") if text not in {"", "-0"} else "0.0"


def _vector(method: str, values: tuple[float, float, float]) -> str:
    return f".{method}({', '.join(_number(value) for value in values)})"


def _key(variable: str, key: ExportKey) -> str:
    return (
        f"Key({variable}, {key.tick}, {key.interpolation.title()})"
        f"{_vector('Position', key.position)}{_vector('Rotation', key.rotation)}"
        f"{_vector('Scale', key.scale)};"
    )


def _point_location(point_tick: int, segment: ExportSegment) -> str:
    if point_tick == segment.start_tick:
        return "Start"
    if point_tick == segment.end_tick:
        return "End"
    return _number((point_tick - segment.start_tick) / (segment.end_tick - segment.start_tick), 8)


def render_clip(model: ExportAnimationModel) -> str:
    lines = [HEADER, "namespace JDH.Animation;", "", f"class {class_name(model.resource_id, 'Clip')} : AnimationClipResource", "{", "    public override void Build()", "    {", f'        Id("{model.clip_id}");', f'        Rig("{model.rig_id}");', f"        Duration({model.duration_ticks});", ""]
    variables: dict[str, str] = {}
    for segment in model.segments:
        variable = identifier(segment.name)
        variables[segment.name] = variable
        lines.append(f'        var {variable} = Segment("{segment.name}", from: {segment.start_tick}, to: {segment.end_tick});')
    loop = model.segment("loop")
    if loop:
        lines.append(f"        Loop({variables[loop.name]}, seam: {model.loop_seam.title()});")
        if model.authored_speed > 0:
            lines.append(f"        Speed({variables[loop.name]}, blocksPerSecond: {_number(model.authored_speed)});")
    for point in model.points:
        segment = next((item for item in model.segments if item.name == point.segment), None)
        if segment:
            lines.append(f'        Point({variables[segment.name]}, "{point.name}", at: {_point_location(point.tick, segment)});')
        else:
            lines.append(f'        Point("{point.name}", at: {point.tick});')
    for event in model.events:
        payload = f', payload: "{_escape(event.payload)}"' if event.payload else ""
        lines.append(f'        Event("{event.name}", at: {event.tick}{payload});')
    if model.root_motion.mode != "DISABLED":
        lines.append(f'        RootMotion({model.root_motion.mode.title()}, bone: "{model.root_motion.bone}");')
    lines.append("")
    for track in model.tracks:
        variable = identifier(track.bone)
        lines.append(f'        var {variable} = Track("{track.bone}");')
        lines.extend(f"        {_key(variable, key)}" for key in track.keys)
        lines.append("")
    lines.extend(("    }", "}", ""))
    return "\n".join(lines)


def _escape(value: str) -> str:
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def _animation_marker(event, model: ExportAnimationModel) -> tuple[str, int]:
    enter, exit_segment = model.segment("enter"), model.segment("exit")
    if enter and event.tick < enter.end_tick:
        return "ENTER", max(0, event.tick - enter.start_tick)
    if exit_segment and event.tick >= exit_segment.start_tick:
        return "EXIT", max(0, event.tick - exit_segment.start_tick)
    main = model.segment("main") or model.segment("loop")
    return "MAIN", max(0, event.tick - (main.start_tick if main else 0))


def render_animation(model: ExportAnimationModel) -> str:
    lines = [HEADER, "namespace JDH.Animation;", "", f"class {class_name(model.resource_id, 'Animation')} : AnimationResource", "{", "    public override void Build()", "    {", f'        Id("{model.resource_id}");', "", f'        var channel = Channel("{model.channel.lower()}");']
    if model.bone_mask and model.bone_mask != "BODY":
        lines.append(f'        Mask(channel, "{model.bone_mask.lower()}");')
    lines.extend((f'        var source = State(channel, "{model.source_state}");', f'        var active = State(channel, "{model.active_state}");', f'        var target = State(channel, "{model.target_state}");', f'        var motion = Clip("{model.clip_id}");', ""))
    enter, loop = model.segment("enter"), model.segment("loop")
    exit_segment, main = model.segment("exit"), model.segment("main")
    if enter:
        lines.append(f'        Enter(active, from: source, play: motion.Segment("{enter.name}"));')
    if model.animation_type in {"ONE_SHOT", "ONE_SHOT_HOLD"}:
        play = f'motion.Segment("{main.name}")' if main else "motion"
        lines.append(f"        OneShot(channel, play: {play});")
    elif model.animation_type == "STATEFUL_HOLD":
        hold = next((point for point in model.points if point.kind == "HOLD"), None)
        if hold:
            lines.append(f'        Hold(active, pose: motion.Point("{hold.name}"));')
    elif loop:
        lines.append(f'        Loop(active, play: motion.Segment("{loop.name}"));')
    if exit_segment:
        point = next((item for item in model.points if item.segment == exit_segment.name or item.name == "neutral"), None)
        at = f', at: motion.Point("{point.name}")' if point else ""
        lines.append(f'        Exit(active, to: target, play: motion.Segment("{exit_segment.name}"){at});')
    if model.hold_last_frame:
        lines.append("        HoldLastFrame();")
    if model.blend_in_ticks > 0:
        lines.append(f"        BlendIn({model.blend_in_ticks});")
    if model.blend_out_ticks > 0:
        lines.append(f"        BlendOut({model.blend_out_ticks});")
    if model.fallback_blend_ticks > 0:
        lines.append(f"        Fallback(channel, Crossfade({model.fallback_blend_ticks}));")
    for event in model.events:
        if event.name in ITEM_MARKERS:
            phase, tick = _animation_marker(event, model)
            lines.append(f'        Marker("{event.name}", phase: {phase}, tick: {tick});')
    lines.extend(("        Recovery(Bounded, checkpointEvery: 3);", "        Replay(RejectIfRunning);", "    }", "}", ""))
    return "\n".join(lines)
