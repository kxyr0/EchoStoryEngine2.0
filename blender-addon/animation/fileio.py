from __future__ import annotations

import os
import tempfile
from pathlib import Path

from .serialization import HEADER


def overwrite_allowed(path: Path, policy: str, confirmed: bool = False) -> tuple[bool, str]:
    if not path.exists():
        return True, "new"
    if policy == "NEVER":
        return False, "existing files are protected"
    if policy == "ASK" and not confirmed:
        return False, "confirmation required"
    if policy == "GENERATED":
        try:
            existing = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            return False, "existing file is not UTF-8 text"
        if not existing.startswith(HEADER):
            return False, "existing file was not generated by the Echo Blender add-on"
    return True, "overwrite"


def atomic_write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    handle, temporary = tempfile.mkstemp(prefix=path.name + ".", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as stream:
            stream.write(content)
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, path)
    except Exception:
        try:
            os.unlink(temporary)
        except FileNotFoundError:
            pass
        raise
